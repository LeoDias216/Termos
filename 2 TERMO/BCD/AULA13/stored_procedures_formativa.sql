-- 8. alterar_preco(...) impedindo valor <= 0
DELIMITER $$
CREATE PROCEDURE ATUALIZAR_PRECO_PRODUTO (
    IN P_ID_PRODUTO INT,
    IN P_NOVO_PRECO DECIMAL(10,2)
)
BEGIN
    IF P_NOVO_PRECO > 0 THEN
        UPDATE PRODUTO
        SET PRECO = P_NOVO_PRECO
        WHERE ID_PRODUTO = P_ID_PRODUTO;

        SELECT 'PREÇO ATUALIZADO' AS MENSAGEM;
    ELSE
        SELECT 'PREÇO INVÁLIDO' AS MENSAGEM;
    END IF;
END $$

CALL ATUALIZAR_PRECO_PRODUTO(4,20);
SELECT * FROM PRODUTO;

-- 9. criar_pedido(IN p_id_cliente INT, OUT p_id_pedido INT)
DELIMITER $$
CREATE PROCEDURE REGISTRAR_PEDIDO (
    IN P_ID_CLIENTE INT,
    OUT P_ID_PEDIDO INT
)
BEGIN
    START TRANSACTION;
    INSERT INTO PEDIDO (
        ID_CLIENTE,
        DATA_PEDIDO,
        STATUS_PEDIDO
    )

    VALUES (
        P_ID_CLIENTE, NOW(), 'PAGO'
    );

    SET P_ID_PEDIDO = LAST_INSERT_ID();
    COMMIT;
END $$

CALL REGISTRAR_PEDIDO(4, @PEDIDO);
