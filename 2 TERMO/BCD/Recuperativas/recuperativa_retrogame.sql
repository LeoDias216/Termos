-- 2.
CREATE TABLE CLIENTE (
    ID_CLIENTE INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_EMAIL UNIQUE (EMAIL)
);

-- 3.
CREATE TABLE PLATAFORMA (
    ID_PLATAFORMA INT AUTO_INCREMENT,
    NOME VARCHAR(80) NOT NULL UNIQUE,
    CONSTRAINT PK_PLATAFORMA PRIMARY KEY (ID_PLATAFORMA),
    CONSTRAINT UQ_NOME UNIQUE (NOME)
);

CREATE TABLE CATEGORIA (
    ID_CATEGORIA INT AUTO_INCREMENT,
    DESCRICAO VARCHAR(80) NOT NULL UNIQUE,
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UQ_DESCRICAO UNIQUE (DESCRICAO)
);

-- 4.
CREATE TABLE JOGO (
    ID_JOGO INT AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    CODIGO VARCHAR(15) NOT NULL UNIQUE,
    ANO_LANCAMENTO INT NOT NULL,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 CHECK (QUANTIDADE_DISPONIVEL >= 0),
    CONSTRAINT PK_JOGO PRIMARY KEY (ID_JOGO),
    CONSTRAINT UQ_CODIGO UNIQUE (CODIGO),
    ID_PLATAFORMA INT NOT NULL,
    ID_CATEGORIA INT NOT NULL,
    CONSTRAINT FK_PLATAFORMA_JOGO FOREIGN KEY (ID_PLATAFORMA) REFERENCES PLATAFORMA (ID_PLATAFORMA),
    CONSTRAINT FK_CATEGORIA_JOGO FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA)
);

-- 5.
CREATE TABLE LOCACAO (
    ID_LOCACAO INT AUTO_INCREMENT,
    DATA_RETIRADA DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_LOCACAO VARCHAR(20) DEFAULT 'ABERTA' CHECK (STATUS_LOCACAO IN ('ABERTA', 'DEVOLVIDA', 'ATRASADA')),
    CONSTRAINT PK_LOCACAO PRIMARY KEY (ID_LOCACAO),
    ID_CLIENTE INT NOT NULL,
    ID_JOGO INT NOT NULL,
    CONSTRAINT FK_CLIENTE_LOCACAO FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE) ON DELETE RESTRICT,
    CONSTRAINT FK_JOGO_LOCACAO FOREIGN KEY (ID_JOGO) REFERENCES JOGO (ID_JOGO) ON DELETE RESTRICT
);

